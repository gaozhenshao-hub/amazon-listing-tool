CREATE TABLE IF NOT EXISTS design_chat_turns (
  id varchar(36) PRIMARY KEY,
  conversationId varchar(36) NOT NULL,
  workspaceId int NOT NULL,
  userId int NOT NULL,
  requestId varchar(36) NOT NULL,
  userText text NOT NULL,
  referenceIds json NOT NULL,
  params json NOT NULL,
  status varchar(24) NOT NULL DEFAULT 'queued',
  providerId int NOT NULL,
  reply text NULL,
  plan json NULL,
  generationId varchar(36) NULL,
  errorText varchar(500) NULL,
  usageInfo json NULL,
  leaseToken varchar(36) NULL,
  leaseUntil datetime(3) NULL,
  createdAt datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  finishedAt datetime(3) NULL,
  UNIQUE KEY design_chat_request_once (workspaceId,userId,requestId),
  INDEX design_chat_history (conversationId,createdAt,id),
  INDEX design_chat_queue (status,leaseUntil)
);
