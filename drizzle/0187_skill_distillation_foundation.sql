  `reviewNote` text,
  `createdBy` int NOT NULL,
  `approvedAt` timestamp NULL,
  `invalidatedAt` timestamp NULL,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_kdistill_evidence_key` (`evidenceKey`),
  UNIQUE KEY `uq_kdistill_evidence_project_source_claim` (`distillationProjectId`,`sourceKey`,`claim`(191)),
  KEY `idx_kdistill_evidence_project_status` (`distillationProjectId`,`status`)
);

