CREATE TABLE IF NOT EXISTS `knowledge_distillation_projects` (
  `id` int NOT NULL AUTO_INCREMENT,
  `workspaceId` int NOT NULL,
  `projectKey` varchar(80) NOT NULL,
  `name` varchar(255) NOT NULL,
  `description` text,
  `status` enum('setup','ready','draft_review','paused','archived') NOT NULL DEFAULT 'setup',
  `profile` json NOT NULL,
  `sourcePolicy` json NOT NULL,
  `createdBy` int NOT NULL,
  `updatedBy` int,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_kdistill_project_workspace_key` (`workspaceId`,`projectKey`),
  KEY `idx_kdistill_project_workspace_status` (`workspaceId`,`status`)
);

CREATE TABLE IF NOT EXISTS `knowledge_distillation_sources` (
  `id` int NOT NULL AUTO_INCREMENT,
  `sourceKey` varchar(80) NOT NULL,
  `workspaceId` int NOT NULL,
  `distillationProjectId` int NOT NULL,
  `sourceDomain` enum('products','listings','images','skills','videos') NOT NULL,
  `sourceTable` varchar(128) NOT NULL,
  `sourceRowId` varchar(128) NOT NULL,
  `sourceContentHash` varchar(64) NOT NULL,
  `sourceStatus` enum('eligible','invalidated','excluded') NOT NULL DEFAULT 'eligible',
  `sourceSummary` text,
  `sourceMetadata` json,
  `selectedBy` int NOT NULL,
  `confirmedBy` int,
  `confirmedAt` timestamp NULL,
  `invalidatedAt` timestamp NULL,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_kdistill_source_key` (`sourceKey`),
  UNIQUE KEY `uq_kdistill_source_identity` (`distillationProjectId`,`sourceTable`,`sourceRowId`,`sourceContentHash`),
  KEY `idx_kdistill_source_project_status` (`distillationProjectId`,`sourceStatus`),
  KEY `idx_kdistill_source_workspace_domain` (`workspaceId`,`sourceDomain`)
);

CREATE TABLE IF NOT EXISTS `knowledge_distillation_evidence` (
  `id` int NOT NULL AUTO_INCREMENT,
  `evidenceKey` varchar(80) NOT NULL,
  `workspaceId` int NOT NULL,
